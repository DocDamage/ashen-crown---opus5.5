def sections():
    out = {}
    cur = None
    for ln in open(MAPFILE, encoding="utf-8"):
        ln = ln.rstrip("\n")
        if ln.startswith("=== "):
            cur = {"id": ln[4:].strip(), "legend": {}, "grid": [], "ents": [], "mode": "hdr"}
            out[cur["id"]] = cur
            continue
        if cur is None:
            continue
        s = ln.strip()
        if cur["mode"] == "hdr":
            if s.startswith("legend:"):
                for p in s[7:].split():
                    k, v = p.split("=", 1)
                    cur["legend"][k] = v
            elif s == "grid:":
                cur["mode"] = "grid"
        elif cur["mode"] == "grid":
            if s.startswith("entities:"):
                cur["mode"] = "ent"
            elif s:
                cur["grid"].append([cur["legend"].get(c, "water") for c in s])
        elif s and not s.startswith("#"):
            cur["ents"].append(s.split())
    return out


