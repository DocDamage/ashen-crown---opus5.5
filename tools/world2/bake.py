def bake(sec, post, deep):
    mid = sec["id"]
    grid = sec["grid"]
    H, W = len(grid), max(len(r) for r in grid)
    for r in grid:
        while len(r) < W:
            r.append("water")
    rng = random.Random(zlib.crc32(mid.encode()))
    k = lambda x, y: grid[y][x] if 0 <= x < W and 0 <= y < H else ("wall_rock" if deep else "deep")
    noise = wgen.value_noise(H, W, 5, 77 + len(mid))
    noise2 = wgen.value_noise(H, W, 3, 91 + len(mid))

    # ground under every cell: own kind, or the most common base kind nearby (for forest/hills/mountain/road...)
    def base_of(x, y):
        kk = grid[y][x]
        if kk in BASEK:
            return kk
        cnt = {}
        for r in (1, 2, 3, 5):
            for dy in range(-r, r + 1):
                for dx in range(-r, r + 1):
                    v = k(x + dx, y + dy)
                    if v in BASEK:
                        cnt[v] = cnt.get(v, 0) + 1
            if cnt:
                return max(cnt, key=cnt.get)
        return "cave_floor" if deep else "plains"
    base0 = [[base_of(x, y) for x in range(W)] for y in range(H)]
    # region edges drawn ragged: the look of the ground is taken from a noise-displaced cell (gameplay keeps the grid)
    ox = (wgen.fbm(H, W, 301 + len(mid), cells=(16, 8, 4)) - 0.5) * 18
    oy = (wgen.fbm(H, W, 419 + len(mid), cells=(16, 8, 4)) - 0.5) * 18
    base = [[base0[min(H - 1, max(0, y + int(round(oy[y, x]))))][min(W - 1, max(0, x + int(round(ox[y, x]))))]
             for x in range(W)] for y in range(H)]
    for y in range(H):
        for x in range(W):
            if base0[y][x] in ("snow",) and grid[y][x] in ("forest", "mountain", "hills"):
                base[y][x] = base0[y][x]
    bg = (10, 8, 12, 255) if deep else (24, 44, 92, 255)
    cv = Image.new("RGBA", (W * T, H * T), bg)

    # 1) ground everywhere (under water too, so smooth shorelines have land beneath), each kind a blended autotile
    first = "dark" if deep else "plains"
    autolayer(cv, {(x, y): GROUND[first] for y in range(H) for x in range(W)}, W, H, lambda x, y: True)
    kinds = sorted({GROUND_OF.get(base[y][x], "plains") for y in range(H) for x in range(W)} - {first})
