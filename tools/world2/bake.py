class Atlas:
    """All billboard sprites packed into one sheet (frames side by side)."""

    def __init__(self):
        self.items = {}
        self.imgs = []

    def get(self, name):
        if name in self.items:
            return self.items[name]
        spec = S[name]
        if spec[0] == "C":
            sh = _img("characters", spec[1])
            fw, fh = sh.width // 3, sh.height // 4
            frames = [sh.crop((fw, 0, 2 * fw, fh))]
        else:
            sh = SHEETS[spec[0]]
            c, r, cw, ch = spec[1:5]
            nf = spec[5] if len(spec) > 5 else 1
            frames = [sh.crop(((c + i * cw) * T, r * T, (c + i * cw + cw) * T, (r + ch) * T)) for i in range(nf)]
        bb = None
        for f in frames:
            b = f.getbbox()
            if b:
                bb = b if bb is None else (min(bb[0], b[0]), min(bb[1], b[1]), max(bb[2], b[2]), max(bb[3], b[3]))
        if bb is None:
            bb = (0, 0, 1, 1)
        frames = [f.crop(bb) for f in frames]
        self.imgs.append((name, frames))
        self.items[name] = None
        return name

    def pack(self):
        """-> atlas image, {name: (sx, sy, sw, sh, frames)}"""
        rows, x, y, rowh, width = {}, 0, 0, 0, 1024
        pos = {}
        for name, frames in self.imgs:
            w, h = frames[0].width * len(frames), frames[0].height
            if x + w > width:
                x, y, rowh = 0, y + rowh + 2, 0
            pos[name] = (x, y, frames[0].width, h, len(frames))
            x += w + 2
            rowh = max(rowh, h)
        im = Image.new("RGBA", (width, y + rowh + 2), (0, 0, 0, 0))
        for name, frames in self.imgs:
            sx, sy, sw, sh, n = pos[name]
            for i, f in enumerate(frames):
                im.paste(f, (sx + i * sw, sy))
        return im, pos


def pick(options, key):
    h = int(hashlib.md5(key.encode()).hexdigest()[:8], 16)
    return options[h % len(options)]


