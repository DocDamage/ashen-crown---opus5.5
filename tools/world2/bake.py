_qcache = {}


def quarters(block, n, s, w, e, nw, ne, sw, se):
    key = (id(block[0]), block[1], block[2], n, s, w, e, nw, ne, sw, se)
    t = _qcache.get(key)
    if t is not None:
        return t
    img, bc, br = block
    bx, by = bc * T, br * T
    out = Image.new("RGBA", (T, T), (0, 0, 0, 0))
    for (qx, qy) in ((0, 0), (1, 0), (0, 1), (1, 1)):
        v = n if qy == 0 else s
        h = w if qx == 0 else e
        d = (nw if qx == 0 else ne) if qy == 0 else (sw if qx == 0 else se)
        if v and h and d:
            sx, sy = 2 - qx, 4 - qy
        elif v and h:
            sx, sy = 2 + qx, qy
        elif v:
            sx, sy = (0 if qx == 0 else 3), 4 - qy
        elif h:
            sx, sy = 2 - qx, (2 if qy == 0 else 5)
        else:
            sx, sy = (0 if qx == 0 else 3), (2 if qy == 0 else 5)
        out.alpha_composite(img.crop((bx + sx * Q, by + sy * Q, bx + sx * Q + Q, by + sy * Q + Q)), (qx * Q, qy * Q))
    _qcache[key] = out
    return out


def autolayer(canvas, cells, W, H, group):
    """cells {(x, y): block}; group(x, y) -> hashable; neighbours join when equal (off-map joins)."""
    for (x, y), blk in cells.items():
        g = group(x, y)

        def same(xx, yy):
            return not (0 <= xx < W and 0 <= yy < H) or group(xx, yy) == g
        t = quarters(blk, same(x, y - 1), same(x, y + 1), same(x - 1, y), same(x + 1, y), same(x - 1, y - 1),
                     same(x + 1, y - 1), same(x - 1, y + 1), same(x + 1, y + 1))
        canvas.alpha_composite(t, (x * T, y * T))


def interior(block):
    return quarters(block, *([True] * 8))


def tiled(tile, w, h):
    im = Image.new("RGBA", (w, h))
    for y in range(0, h, tile.height):
        for x in range(0, w, tile.width):
            im.paste(tile, (x, y))
    return im


