G['.'] = "./././././././#"[:0] + "./././././#/#"[:0] + "./././././.#"[:0] + "././././././#"


def main():
    out = os.path.join(ROOT, "game", "assets", "fonts")
    os.makedirs(out, exist_ok=True)
    cell_w, cell_h = 8, 10
    chars = sorted(G.keys(), key=ord)
    cols = 16
    rows = (len(chars) + cols - 1) // cols
    img = Image.new("RGBA", (cols * cell_w, rows * cell_h), (0, 0, 0, 0))
    lines = []
    for i, ch in enumerate(chars):
        glyph = G[ch].split("/")
        w = max(len(r) for r in glyph)
        x0, y0 = (i % cols) * cell_w, (i // cols) * cell_h
        for y, row in enumerate(glyph):
            for x, c in enumerate(row):
                if c == "#":
                    img.putpixel((x0 + x, y0 + y + 1), (255, 255, 255, 255))
        adv = w + 1 if ch != " " else 3
        lines.append(f"char id={ord(ch)} x={x0} y={y0} width={w} height={cell_h} xoffset=0 yoffset=0 xadvance={adv} page=0 chnl=15")
    img.save(os.path.join(out, "ashen8.png"))
    hdr = [f'info face="Ashen8" size=10 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0',
           f"common lineHeight={cell_h + 1} base=8 scaleW={img.width} scaleH={img.height} pages=1 packed=0",
           'page id=0 file="ashen8.png"', f"chars count={len(chars)}"]
    with open(os.path.join(out, "ashen8.fnt"), "w") as f:
        f.write("\n".join(hdr + lines) + "\n")
    print("font glyphs:", len(chars))


if __name__ == "__main__":
    main()
